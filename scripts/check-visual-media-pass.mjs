import { chromium, devices } from "playwright";

const base = process.env.CUEFLOW_URL || "http://127.0.0.1:4175";
const browser = await chromium.launch({ headless: true, executablePath: "/usr/bin/chromium", args: ["--no-sandbox", "--disable-gpu"] });
const errors = [];
const context = await browser.newContext({ viewport: { width: 1280, height: 800 } });
const page = await context.newPage();
page.on("pageerror", error => errors.push(error.message));
await page.goto(`${base}/`, { waitUntil: "networkidle" });
const home = await page.locator("nav.home-nav").count();
const homeShots = await page.locator('img[src*="/shots/"]').evaluateAll(images => images.map(image => image.getAttribute("src") || ""));
const forbidden = homeShots.filter(src => /keyboard-control-new|crew-handoff-new/i.test(src));
await page.goto(`${base}/studio`, { waitUntil: "networkidle" });
await page.addStyleTag({ content: '[role="dialog"] { display: none !important; }' });
const workspaceNav = page.locator("nav.workspace-nav");
const workspace = await workspaceNav.count();
const workspaceBefore = workspace ? await workspaceNav.evaluate(el => getComputedStyle(el).transform) : "";
if (workspace) await workspaceNav.hover();
await page.waitForTimeout(340);
const workspaceAfter = workspace ? await workspaceNav.evaluate(el => getComputedStyle(el).transform) : "";
const mediaCards = await page.locator(".media-card").count();
const mediaPreviews = await page.locator(".media-card .media-preview").count();
const phoneContext = await browser.newContext({ ...devices["iPhone 13"] });
const phone = await phoneContext.newPage();
await phone.goto(`${base}/`, { waitUntil: "networkidle" });
const phoneShot = await phone.locator('source[media="(max-width: 639px)"]').count();
console.log(JSON.stringify({ home, workspace, workspaceBefore, workspaceAfter, homeShots, forbidden, mediaCards, mediaPreviews, phoneShot, errors }, null, 2));
await phoneContext.close();
await context.close();
await browser.close();
if (errors.length || home !== 1 || workspace !== 1 || workspaceBefore === workspaceAfter || forbidden.length || mediaCards < 0 || mediaPreviews < 0 || phoneShot !== 5) process.exit(1);
