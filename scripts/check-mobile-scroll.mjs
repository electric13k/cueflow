import { chromium, devices } from "playwright";

const base = process.env.CUEFLOW_URL || "https://5177-id2uudnq630vo4xwq7j8n-e90bf284.us3.manus.computer";
const browser = await chromium.launch({ headless: true, executablePath: "/usr/bin/chromium", args: ["--no-sandbox", "--disable-gpu"] });
const context = await browser.newContext({ ...devices["iPhone 13"], reducedMotion: "reduce" });
const page = await context.newPage();
const errors = [];
page.on("pageerror", error => errors.push(error.message));
await page.goto(`${base}/studio`, { waitUntil: "networkidle" });
await page.waitForTimeout(500);
const accept = page.getByRole("button", { name: "Accept", exact: true });
if (await accept.count()) await accept.click();
await page.addStyleTag({ content: '[role="dialog"] { display: none !important; }' });
console.log(JSON.stringify({ url: page.url(), title: await page.title(), deckButtons: await page.locator('button[data-tour="pane-deck"]').count(), libraryButtons: await page.locator('button[data-tour="pane-library"]').count(), bodyText: (await page.locator("body").innerText()).slice(0, 500) }, null, 2));
const panes = await page.getByRole("button", { name: /^(Library|Deck|Shows|Script)$/ }).allTextContents();
await page.evaluate(() => window.scrollTo({ top: document.documentElement.scrollHeight, behavior: "auto" }));
await page.waitForTimeout(80);
const before = await page.evaluate(() => window.scrollY);
await page.locator('button[data-tour="pane-deck"]').click();
await page.waitForTimeout(160);
const afterDeck = await page.evaluate(() => window.scrollY);
await page.evaluate(() => window.scrollTo({ top: document.documentElement.scrollHeight, behavior: "auto" }));
await page.waitForTimeout(80);
await page.locator('button[data-tour="pane-library"]').click();
await page.waitForTimeout(160);
const afterLibrary = await page.evaluate(() => window.scrollY);
console.log(JSON.stringify({ viewport: await page.evaluate(() => ({ width: innerWidth, height: innerHeight })), panes, before, afterDeck, afterLibrary, errors }, null, 2));
await browser.close();
if (errors.length || afterDeck > 4 || afterLibrary > 4) process.exit(1);
